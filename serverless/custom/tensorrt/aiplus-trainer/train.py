def _normalize_names(names):
    """Normalize Ultralytics names into a list of strings sorted by class index."""
    if isinstance(names, dict):
        try:
            items = sorted(((int(k), v) for k, v in names.items()), key=lambda x: x[0])
        except Exception:
            # keys might already be ints
            items = sorted(names.items(), key=lambda x: int(x[0]))
        return [str(v) for _, v in items]
    if isinstance(names, list):
        return [str(x) for x in names]
    return None

def write_engine_metadata_sidecar(engine_path: Path, names, imgsz: int):
    """Write a YAML sidecar with minimal metadata so Ultralytics can map class ids to names."""
    names_list = _normalize_names(names)
    if not names_list:
        return
    meta = {
        "task": "detect",
        "imgsz": int(imgsz),
        "nc": len(names_list),
        "names": names_list,
    }
    sidecar = Path(engine_path).with_suffix(".yaml")
    try:
        with open(sidecar, "w", encoding="utf-8") as f:
            yaml.safe_dump(meta, f, sort_keys=False, allow_unicode=True)
        print(f"[INFO] Wrote engine metadata sidecar: {sidecar}")
    except Exception as e:
        print(f"[WARN] Failed to write engine metadata sidecar: {e}")

def build_engine_with_trtexec(onnx_path: Path, trtexec: str, imgsz: int, workspace: int, half: bool,
                              min_b: int, opt_b: int, max_b: int, onnx_input: str, engine_out: str | None):
    H = W = imgsz
    shape_flag = (
        f" --minShapes={onnx_input}:{min_b}x3x{H}x{W}"
        f" --optShapes={onnx_input}:{opt_b}x3x{H}x{W}"
        f" --maxShapes={onnx_input}:{max_b}x3x{H}x{W}"
    )
    precision = " --fp16" if half else ""
    onnx_p = Path(onnx_path)
    out_path = engine_out or str(onnx_p.with_name(onnx_p.stem + f"_b{max_b}.engine"))
    cmd = (
        f"{trtexec} --onnx={onnx_path} --saveEngine={out_path}"
        f" --workspace={workspace}" + precision + shape_flag
    )
    print("[INFO] Building TensorRT engine with trtexec:\n" + cmd)
    # Optional: ensure trtexec is present
    import shutil as _sh
    if not _sh.which(trtexec):
        raise RuntimeError(f"trtexec not found at '{trtexec}'. Install 'libnvinfer-bin' or pass --trtexec /full/path")
    subprocess.run(cmd, shell=True, check=True)
    print(f"[SUCCESS] Built engine: {out_path}")
    return out_path


def build_engine_with_python_trt(onnx_path: Path, engine_out: str | None, imgsz: int,
                                 min_b: int, opt_b: int, max_b: int, workspace: int,
                                 fp16: bool, int8: bool):
    """Build a TensorRT engine in **Python** (no trtexec) with batch profiles."""
    import tensorrt as trt

    logger = trt.Logger(trt.Logger.INFO)
    EXPL = 1 << int(trt.NetworkDefinitionCreationFlag.EXPLICIT_BATCH)

    H = W = imgsz
    onnx_bytes = Path(onnx_path).read_bytes()

    with trt.Builder(logger) as builder, \
         builder.create_network(EXPL) as network, \
         trt.OnnxParser(network, logger) as parser, \
         builder.create_builder_config() as config:

        #builder.max_batch_size = 1  # unused for explicit, but must be set pre-TRT 10
        config.set_memory_pool_limit(trt.MemoryPoolType.WORKSPACE, workspace * (1 << 20))

        print(f"[INFO] Parsing ONNX: {onnx_path}")
        if not parser.parse(onnx_bytes):
            for i in range(parser.num_errors):
                print("[ONNX] Parse error:", parser.get_error(i))
            raise RuntimeError("Failed to parse ONNX")

        input_tensor = network.get_input(0)
        in_name = input_tensor.name

        profile = builder.create_optimization_profile()
        min_shape = (min_b, 3, H, W)
        opt_shape = (opt_b, 3, H, W)
        max_shape = (max_b, 3, H, W)
        profile.set_shape(in_name, min_shape, opt_shape, max_shape)
        config.add_optimization_profile(profile)

        if fp16 and builder.platform_has_fast_fp16:
            config.set_flag(trt.BuilderFlag.FP16)
        if int8:
            # For real INT8 you need Q/DQ ONNX or a calibrator
            config.set_flag(trt.BuilderFlag.INT8)
            print("[WARN] INT8 set without calibrator: expecting Q/DQ ONNX or provide calibrator in code.")

        print(f"[INFO] Building engine with batch profile: min={min_shape}, opt={opt_shape}, max={max_shape}")
        engine = builder.build_engine(network, config)
        if engine is None:
            raise RuntimeError("Engine build failed")

        out_p = Path(engine_out) if engine_out else Path(onnx_path).with_name(Path(onnx_path).stem + f"_b{max_b}.engine")
        out_p.write_bytes(bytearray(engine.serialize()))
        print(f"[SUCCESS] Saved engine to: {out_p}")
        return str(out_p)


