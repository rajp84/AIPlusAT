#!/usr/bin/env python3
"""
Train a YOLO detector on your dataset and export a TensorRT engine (optionally convert from CVAT YOLO 1.1).

Now includes:
  • Robust CVAT YOLO 1.1 → Ultralytics dataset converter
  • `--check-trt` to print installed TensorRT + CUDA info
  • Safe YAML writing for data.yaml (handles colons, unicode)
  • Engine export paths:
      - Ultralytics .engine export (simple)
      - ONNX → **Python TensorRT builder** (no `trtexec` required)
      - ONNX → trtexec (optional)
  • Batch profiles via flags: --min-batch/--opt-batch/--max-batch (default 1/64/256)
"""

