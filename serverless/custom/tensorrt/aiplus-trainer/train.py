    g.add_argument("--cvat-dir", help="Path to an already-extracted CVAT YOLO 1.1 folder")
    p.add_argument("--out-dataset", help="Where to write the converted dataset (Ultralytics layout)")
    p.add_argument("--val-ratio", type=float, default=0.2, help="Validation split ratio if CVAT export has no split")
    p.add_argument("--symlink", action="store_true", help="Symlink images/labels instead of copying during conversion")

    # Dataset / model for training
    p.add_argument("--data", help="Path to YOLO data.yaml (skip conversion)")
    p.add_argument("--model", default="yolov8s.pt", help="Base model checkpoint (e.g., yolov8s.pt, yolov11s.pt)")

    # Training hyperparams
    p.add_argument("--imgsz", type=int, default=1280, help="Training/inference image size (square)")
    p.add_argument("--epochs", type=int, default=100, help="Number of training epochs")
    p.add_argument("--batch", type=int, default=16, help="Batch size")
    p.add_argument("--device", default="0", help="Device string for Ultralytics (e.g., '0', '0,1', 'cpu')")
    p.add_argument("--workers", type=int, default=8, help="Dataloader workers")
    p.add_argument("--seed", type=int, default=42, help="Random seed")
    p.add_argument("--patience", type=int, default=50, help="Early-stopping patience")

    # Augmentation knobs tuned for small logos/faces
    p.add_argument("--mosaic", type=float, default=1.0)
    p.add_argument("--mixup", type=float, default=0.2)
    p.add_argument("--degrees", type=float, default=10)
    p.add_argument("--translate", type=float, default=0.1)
    p.add_argument("--scale", type=float, default=0.7)
    p.add_argument("--shear", type=float, default=2.0)
    p.add_argument("--perspective", type=float, default=0.0005)
    p.add_argument("--fliplr", type=float, default=0.0)
    p.add_argument("--flipud", type=float, default=0.0)
    p.add_argument("--erasing", type=float, default=0.4)

    # Project layout
    p.add_argument("--project", default="runs/detect", help="Project directory")
    p.add_argument("--name", default=None, help="Run name; default is auto-generated by Ultralytics")

    # Validation/inference thresholds
    p.add_argument("--conf", type=float, default=0.15, help="Confidence threshold for val/track later")
    p.add_argument("--iou", type=float, default=0.6, help="IoU threshold for NMS")

    # Export options
    p.add_argument("--trt-half", action="store_true", help="Export/Build FP16 engine (builder or trtexec)")
    p.add_argument("--trt-dynamic", action="store_true", help="Dynamic shapes for Ultralytics' internal TensorRT export")
    p.add_argument("--trt-workspace", type=int, default=4096, help="TensorRT workspace size in MB (builder/trtexec)")
    p.add_argument("--int8", action="store_true", help="INT8 (requires Q/DQ ONNX or calibrator; builder/trtexec)")
    p.add_argument("--onnx-only", action="store_true", help="Skip TensorRT and only export ONNX")

    # Engine build paths
    p.add_argument("--build-with-python-trt", action="store_true", help="Use Python TensorRT builder (no trtexec)")
    p.add_argument("--build-with-trtexec", action="store_true", help="After ONNX export, run trtexec to build engine")
    p.add_argument("--trtexec", default="trtexec", help="Path to trtexec binary (if using trtexec)")

    # Batch profile controls for builder/trtexec
    p.add_argument("--min-batch", type=int, default=1, help="TensorRT min batch profile")
    p.add_argument("--opt-batch", type=int, default=64, help="TensorRT opt batch profile")
    p.add_argument("--max-batch", type=int, default=128, help="TensorRT max batch profile")
