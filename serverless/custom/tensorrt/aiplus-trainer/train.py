def _extract_zip(zip_path: Path) -> Path:
    tmp = Path(tempfile.mkdtemp(prefix="cvat_yolo11_"))
    with zipfile.ZipFile(zip_path, 'r') as z:
        z.extractall(tmp)
    return tmp


def _read_class_names(cvat_root: Path) -> List[str]:
    for name_file in ("obj.names", "classes.txt", "class.names", "obj.names.txt"):
        p = cvat_root / name_file
        if p.exists():
            names = [ln.strip() for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]
            if names:
                return names
    return ["object"]


def _gather_pairs(cvat_root: Path) -> List[Tuple[Path, Path]]:
    pairs = []
    for img in cvat_root.rglob("*"):
        if img.suffix.lower() in IMG_EXTS and img.is_file():
            lbl = img.with_suffix('.txt')
            if lbl.exists():
                pairs.append((img, lbl))
    return pairs


def _split_pairs(pairs: List[Tuple[Path, Path]], val_ratio: float, seed: int) -> Tuple[List, List]:
    random.Random(seed).shuffle(pairs)
    n_val = int(len(pairs) * val_ratio)
    val = pairs[:n_val]
    train = pairs[n_val:]
    return train, val


def _safe_link_or_copy(src: Path, dst: Path, symlink: bool):
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        if symlink:
            if dst.exists() or dst.is_symlink():
                dst.unlink()
            os.symlink(src, dst)
        else:
            shutil.copy2(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def convert_cvat_yolo11(cvat_zip: Path | None, cvat_dir: Path | None, out_dataset: Path, val_ratio: float, symlink: bool, seed: int) -> Path:
    """Convert CVAT YOLO 1.1 export to Ultralytics dataset structure. Returns path to data.yaml."""
    if cvat_zip:
        tmp_root = _extract_zip(cvat_zip)
        cvat_root = tmp_root
    else:
        cvat_root = Path(cvat_dir)
        tmp_root = None

    # Guess actual data root (some exports nest a folder)
    candidates = [cvat_root]
    for sub in cvat_root.iterdir():
        if sub.is_dir():
            candidates.append(sub)
    def count_imgs(p: Path):
        return sum(1 for _ in p.rglob("*") if _.suffix.lower() in IMG_EXTS)
    cvat_data_root = max(candidates, key=count_imgs)

    names = _read_class_names(cvat_root)
    pairs = _gather_pairs(cvat_data_root)
    if not pairs:
        raise RuntimeError("No (image, label) pairs found in CVAT YOLO 1.1 export.")

    train_pairs, val_pairs = _split_pairs(pairs, val_ratio=val_ratio, seed=seed)

    # Write files
    for img, lbl in train_pairs:
        _safe_link_or_copy(img, out_dataset / "images" / "train" / img.name, symlink)
        _safe_link_or_copy(lbl, out_dataset / "labels" / "train" / lbl.name, symlink)
    for img, lbl in val_pairs:
        _safe_link_or_copy(img, out_dataset / "images" / "val" / img.name, symlink)
        _safe_link_or_copy(lbl, out_dataset / "labels" / "val" / lbl.name, symlink)

    # Write data.yaml safely
    data_yaml = out_dataset / "data.yaml"
    data_obj = {
        "path": str(out_dataset.resolve()),
        "train": "images/train",
        "val": "images/val",
        "names": [str(n) for n in names],
    }
    with open(data_yaml, "w", encoding="utf-8") as f:
        yaml.safe_dump(data_obj, f, sort_keys=False, allow_unicode=True)

    if tmp_root and tmp_root.exists():
        shutil.rmtree(tmp_root, ignore_errors=True)

    return data_yaml


