def export_with_fallback(export_model, imgsz: int, dynamic: bool, half: bool, workspace: int, device: str, data_yaml_path: Path | None, trtexec: str):
    """Try Ultralytics TensorRT export first; if it fails, export ONNX and print a trtexec command."""
    try:
        print("[INFO] Exporting to TensorRT via Ultralytics…")
        export_path = export_model.export(
            format="engine",
            half=half,
            dynamic=dynamic,
            imgsz=imgsz,
            workspace=workspace,
            device=device,
            data=str(data_yaml_path) if data_yaml_path else None,
        )
        print(f"[SUCCESS] Exported TensorRT engine: {export_path}")
        return export_path
    except Exception as e:
        print("[WARN] Ultralytics TensorRT export failed. Falling back to ONNX…")
        print(e)

    # ONNX fallback
    onnx_path = export_model.export(format="onnx", imgsz=imgsz, dynamic=True)
    print(f"[SUCCESS] Exported ONNX: {onnx_path}")

    # Compose a trtexec command suggestion
    H = W = imgsz
    min_b, opt_b, max_b = 1, 4, 8
    shape_flag = (
        f" --minShapes=images:{min_b}x3x{H}x{W}"
        f" --optShapes=images:{opt_b}x3x{H}x{W}"
        f" --maxShapes=images:{max_b}x3x{H}x{W}"
    )
    cmd = (
        f"{trtexec} --onnx={onnx_path} --saveEngine={(Path(onnx_path).with_name(Path(onnx_path).stem + '.engine'))}"
        f" --workspace={workspace} --fp16" + shape_flag
    )
    print("[INFO] To build a TensorRT engine with your system's TRT, run:")
    print(cmd)
    return None


