def main():
    try:
        from ultralytics import YOLO
    except Exception as e:
        print("[FATAL] Failed to import ultralytics. Did you 'pip install ultralytics'?", file=sys.stderr)
        raise

    args = parse_args()
    try:
        mp.set_sharing_strategy('file_system')
    except Exception:
        pass
    def write_progress(val: float, extra: dict | None = None):
        try:
            if not args.progress_file:
                return
            payload = {"progress": float(max(0.0, min(1.0, val)))}
            if extra:
                payload.update(extra)
            Path(args.progress_file).parent.mkdir(parents=True, exist_ok=True)
            with open(args.progress_file, "w", encoding="utf-8") as pf:
                json.dump(payload, pf)
        except Exception:
            pass

    if args.check_trt:
        check_trt()
        return

    # 0) Optional: convert CVAT YOLO 1.1 export
    data_yaml_path: Path | None = None
    if args.cvat_zip or args.cvat_dir:
        if not args.out_dataset:
            print("[FATAL] --out-dataset is required when converting CVAT export.", file=sys.stderr)
            sys.exit(2)
        cvat_zip = Path(args.cvat_zip) if args.cvat_zip else None
        cvat_dir = Path(args.cvat_dir) if args.cvat_dir else None
        out_dataset = Path(args.out_dataset)
        print("[INFO] Converting CVAT YOLO 1.1 export → Ultralytics layout…")
        data_yaml_path = convert_cvat_yolo11(
            cvat_zip=cvat_zip,
            cvat_dir=cvat_dir,
            out_dataset=out_dataset,
            val_ratio=args.val_ratio,
            symlink=args.symlink,
            seed=args.seed,
        )
        print(f"[INFO] Wrote dataset to: {out_dataset}")
        print(f"[INFO] Generated data.yaml: {data_yaml_path}")
        # Handler sets 10% after download; ensure we keep at least that
        write_progress(0.1, {"phase": "prepared"})

    # If user supplied --data, that overrides conversion
    if args.data:
        data_yaml_path = Path(args.data)

    if data_yaml_path is None:
        print("[FATAL] Provide either --data or --cvat-zip/--cvat-dir + --out-dataset", file=sys.stderr)
        sys.exit(2)

    # 1) Train
    print("[INFO] Starting training…")
    # Ensure Ultralytics uses mounted runs directory
    try:
        import os as _os
        _os.environ.setdefault("ULTRALYTICS_RUNS_DIR", str(Path(os.environ.get("TMPDIR", "/opt/nuclio/workdir/tmp")).parent / "runs"))
    except Exception:
        pass
    model = YOLO(args.model)

    # Try to hook per-epoch progress callbacks (Ultralytics v8 API)
    def _epoch_cb(trainer):
        try:
            current = int(getattr(trainer, "epoch", 0)) + 1
            total = int(getattr(trainer, "epochs", args.epochs) or args.epochs)
            total = max(1, total)
            per_epoch = 0.8 / float(total)
            completed = max(0, min(current, total))
            frac = 0.1 + per_epoch * completed
            write_progress(frac, {"phase": "training", "epoch": current, "epochs": total})
        except Exception:
            pass
    try:
        # register on both names for broader compatibility
        if hasattr(model, "add_callback"):
            model.add_callback("on_train_epoch_end", _epoch_cb)
            model.add_callback("on_fit_epoch_end", _epoch_cb)
    except Exception:
        pass

    try:
        _ = model.train(
            data=str(data_yaml_path),
            imgsz=args.imgsz,
            epochs=args.epochs,
            batch=args.batch,
            device=args.device,
            workers=args.workers,
            seed=args.seed,
            patience=args.patience,
            project=args.project,
            name=args.name,
            # Augmentations
            mosaic=args.mosaic,
            mixup=args.mixup,
            degrees=args.degrees,
            translate=args.translate,
            scale=args.scale,
            shear=args.shear,
            perspective=args.perspective,
            fliplr=args.fliplr,
            flipud=args.flipud,
            erasing=args.erasing,
            cos_lr=True,
            cache=False,
        )
    except Exception as ex:
        # Mark failed status and re-raise for handler to capture exit code
        write_progress(1.0, {"phase": "failed", "error": str(ex)})
        print(f"[FATAL] Training failed: {ex}", file=sys.stderr)
        raise

    # Mark conversion/export phase start at 90%
    write_progress(0.9, {"phase": "export"})

    # 2) Locate best checkpoint
    try:
        best_pt = find_latest_best_weight()
    except FileNotFoundError:
        best_pt = None
        if hasattr(model, "ckpt_path") and model.ckpt_path and Path(model.ckpt_path).exists():
            best_pt = Path(model.ckpt_path)
        if best_pt is None:
            raise

    print(f"[INFO] Using best weights: {best_pt}")

    # 3) Export → choose path
    export_model = YOLO(str(best_pt))

    # Always get an ONNX when using builder/trtexec; otherwise try direct .engine export
    if args.onnx_only:
        onnx_path = export_model.export(format="onnx", imgsz=args.imgsz, dynamic=True)
        print(f"[SUCCESS] Exported ONNX: {onnx_path}")
        print("[TIP] Build engine with Python TRT (--build-with-python-trt) or trtexec (--build-with-trtexec).")

    elif args.build_with_python_trt:
        onnx_path = export_model.export(format="onnx", imgsz=args.imgsz, dynamic=True)
        print(f"[SUCCESS] Exported ONNX: {onnx_path}")
        engine_path = build_engine_with_python_trt(
            onnx_path=Path(str(onnx_path)),
            engine_out=args.engine_out,
            imgsz=args.imgsz,
            min_b=args.min_batch,
            opt_b=args.opt_batch,
            max_b=args.max_batch,
            workspace=args.trt_workspace,
            fp16=args.trt_half,
            int8=args.int8,
        )
        # Write sidecar metadata next to engine
        try:
            names = getattr(export_model, "names", None)
            if names is None and hasattr(export_model, "model"):
                names = getattr(export_model.model, "names", None)
            if engine_path:
                write_engine_metadata_sidecar(Path(engine_path), names, imgsz=args.imgsz)
        except Exception as _e:
            print(f"[WARN] Could not write metadata sidecar: {_e}")

    elif args.build_with_trtexec:
        onnx_path = export_model.export(format="onnx", imgsz=args.imgsz, dynamic=True)
        print(f"[SUCCESS] Exported ONNX: {onnx_path}")
        try:
            engine_path = build_engine_with_trtexec(
                onnx_path=Path(str(onnx_path)),
                trtexec=args.trtexec,
                imgsz=args.imgsz,
                workspace=args.trt_workspace,
                half=args.trt_half,
                min_b=args.min_batch,
                opt_b=args.opt_batch,
                max_b=args.max_batch,
                onnx_input=args.onnx_input,
                engine_out=args.engine_out,
            )
            # Write sidecar metadata next to engine
            try:
                names = getattr(export_model, "names", None)
                if names is None and hasattr(export_model, "model"):
                    names = getattr(export_model.model, "names", None)
                if engine_path:
                    write_engine_metadata_sidecar(Path(engine_path), names, imgsz=args.imgsz)
            except Exception as _e:
                print(f"[WARN] Could not write metadata sidecar: {_e}")
        except subprocess.CalledProcessError as e:
            print("[ERROR] trtexec build failed:", e)
            print("[HINT] Ensure --onnx-input matches your ONNX input name (default 'images') and TRT/CUDA are compatible.")

    else:
        # Original behavior: try Ultralytics engine export, then fallback to ONNX + printed trtexec command
        export_path = export_with_fallback(
            export_model,
            imgsz=args.imgsz,
            dynamic=args.trt_dynamic,
            half=args.trt_half,
            workspace=args.trt_workspace,
            device=args.device,
            data_yaml_path=data_yaml_path,
            trtexec=args.trtexec,
        )
        # Write sidecar metadata next to engine if we have an engine path
        try:
            names = getattr(export_model, "names", None)
            if names is None and hasattr(export_model, "model"):
                names = getattr(export_model.model, "names", None)
            if export_path:
                # Ultralytics can return Path, list, or str; normalize
                if isinstance(export_path, (list, tuple)) and export_path:
                    engine_candidate = Path(str(export_path[0]))
                else:
                    engine_candidate = Path(str(export_path))
                if engine_candidate.suffix == ".engine":
                    write_engine_metadata_sidecar(engine_candidate, names, imgsz=args.imgsz)
        except Exception as _e:
            print(f"[WARN] Could not write metadata sidecar: {_e}")

    # Done
    write_progress(1.0, {"phase": "done"})

if __name__ == "__main__":
    main()
