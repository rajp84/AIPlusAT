def find_latest_best_weight() -> Path:
    candidates = glob.glob("runs/detect/**/weights/best.pt", recursive=True)
    if not candidates:
        raise FileNotFoundError("No best.pt found under runs/detect/**/weights. Did training complete?")
    latest = max(candidates, key=os.path.getmtime)
    return Path(latest)


def check_trt():
    try:
        import tensorrt as trt  # noqa: F401
        import cuda  # type: ignore  # may not exist; ignore
        ver = getattr(trt, "__version__", "?")
        cuda_ver = getattr(trt, "__cuda_version__", "?")
        print(f"[TRT] TensorRT __version__: {ver}")
        print(f"[TRT] Built against CUDA: {cuda_ver}")
    except Exception as e:
        print("[TRT] TensorRT not importable in this environment:", e)


